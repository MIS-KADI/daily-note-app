/**
 * Translation helper with multi-tier fallback:
 * 1. Requested language (gu, hi, en, es, fr, de, ar)
 * 2. English (en) for international users
 * 3. Gujarati (gu) as default base
 * 4. Raw key if nothing found
 */
export const t = (key, lang = 'gu') => {
  if (translations[key]) {
    if (translations[key][lang]) {
      return translations[key][lang];
    }
    if (translations[key]['en']) {
      return translations[key]['en'];
    }
    if (translations[key]['gu']) {
      return translations[key]['gu'];
    }
  }
  return key;
};
